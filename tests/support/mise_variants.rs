pub struct Upstream;

impl Resolver for Upstream {
    fn resolve(&self, _tool: &str, request: &str) -> Result<String, StackError> {
        Ok(request.into())
    }

    fn registry_backend(&self, _tool: &str) -> Result<Option<String>, StackError> {
        Ok(None)
    }
}

#[derive(Debug, Clone)]
pub struct Call {
    pub tools: Vec<String>,
    pub platforms: Vec<String>,
    pub seed: String,
}

pub struct FakeMise {
    /// Keys whose table "upstream" now serves with a different checksum.
    pub changed: Mutex<Vec<String>>,
    /// Keys mise produced nothing for this time (offline, or not published).
    pub unpublished: Mutex<Vec<String>>,
    pub calls: Mutex<Vec<Call>>,
}

impl FakeMise {
    pub fn new() -> Arc<Self> {
        Arc::new(Self { changed: Mutex::new(vec![]), unpublished: Mutex::new(vec![]), calls: Mutex::new(vec![]) })
    }

    pub fn calls(&self) -> Vec<Call> {
        self.calls.lock().unwrap().clone()
    }

    /// The keys mise writes for one requested platform.
    fn written(tool: &str, platform: &str) -> Vec<String> {
        let qualified = platform.splitn(3, '-').nth(2).is_some();
        let variants: &[&str] = match (tool, platform) {
            ("bun", _) if qualified => &[],
            ("bun", "linux-x64") => &["baseline", "musl", "musl-baseline"],
            ("bun", "linux-arm64") => &["musl"],
            ("bun", "macos-x64") | ("bun", "windows-x64") => &["baseline"],
            _ => &[],
        };
        std::iter::once(platform.to_string()).chain(variants.iter().map(|v| format!("{platform}-{v}"))).collect()
    }

    fn table(&self, tool: &str, version: &str, key: &str) -> Option<Value> {
        if self.unpublished.lock().unwrap().iter().any(|k| k == key) {
            return None;
        }
        let real = match (tool, version) {
            ("bun", "1.3.0") => Some(REAL_BUN),
            ("node", "24.13.0") => Some(REAL_NODE),
            _ => None,
        };
        let mut table = real
            .and_then(|text| toml::from_str::<Table>(text).ok())
            .and_then(|lock| lock["tools"][tool][0].get(format!("platforms.{key}")).cloned())
            .unwrap_or_else(|| {
                let mut t = Table::new();
                t.insert("checksum".into(), format!("sha256:{tool}-{version}-{key}").into());
                t.insert("url".into(), format!("https://example.invalid/{tool}/{version}/{key}").into());
                t.into()
            });
        if self.changed.lock().unwrap().iter().any(|k| k == key) {
            table.as_table_mut().unwrap().insert("checksum".into(), format!("sha256:upstream-changed-{key}").into());
        }
        Some(table)
    }
}

impl Locker for FakeMise {
    fn version(&self, _: &Path) -> Result<CalVer, StackError> {
        Ok(CalVer(2026, 10, 3))
    }

    fn lock(&self, scratch: &ScratchRoot, platforms: &[String], tools: &[String]) -> Result<LockRun, StackError> {
        let lock_path = scratch.path().join(".config/mise/mise.lock");
        let seed = fs::read_to_string(&lock_path).unwrap();
        let config: Table = toml::from_str(&fs::read_to_string(scratch.config_path()).unwrap()).unwrap();
        self.calls.lock().unwrap().push(Call { tools: tools.into(), platforms: platforms.into(), seed: seed.clone() });
        let mut lock: Table = toml::from_str(&seed).unwrap();
        let mut stderr = String::new();
        for tool in tools {
            let version = match &config["tools"][tool.as_str()] {
                Value::String(s) => s.clone(),
                Value::Table(t) => t["version"].as_str().unwrap().into(),
                other => panic!("{other}"),
            };
            let mut entry = Table::new();
            entry.insert("version".into(), version.clone().into());
            entry.insert("backend".into(), format!("core:{tool}").into());
            entry.insert("specifiers".into(), Value::Array(vec![version.clone().into()]));
            for platform in platforms {
                for key in Self::written(tool, platform) {
                    match self.table(tool, &version, &key) {
                        Some(t) => {
                            entry.insert(format!("platforms.{key}"), t);
                        }
                        None => stderr.push_str(&format!("mise WARN  failed to lock {tool}@{version} for {key}: not available\n")),
                    }
                }
            }
            let tools = lock.entry("tools").or_insert_with(|| Table::new().into()).as_table_mut().unwrap();
            tools.insert(tool.clone(), Value::Array(vec![entry.into()]));
        }
        fs::write(&lock_path, toml::to_string_pretty(&lock).unwrap()).unwrap();
        Ok(LockRun { exit_code: Some(0), stderr })
    }
}

pub struct Sandbox {
    pub tmp: TempDir,
    pub locker: Arc<dyn Locker>,
}

impl Sandbox {
    pub fn new(stack_toml: &str, locker: Arc<dyn Locker>) -> Self {
        let sb = Self { tmp: TempDir::new().unwrap(), locker };
        fs::create_dir_all(sb.root()).unwrap();
        sb.write(stack_toml);
        sb
    }

    pub fn root(&self) -> PathBuf {
        self.tmp.path().join("app")
    }

    pub fn write(&self, stack_toml: &str) {
        fs::write(self.root().join("stack.toml"), stack_toml).unwrap();
    }

    pub fn compile(&self, mode: Mode) -> Result<Report, StackError> {
        compile(&Options {
            root: self.root(),
            mode,
            write: true,
            cache: self.tmp.path().join("cache"),
            state: self.tmp.path().join("state"),
            reassign_ports: false,
            resolver: Some(Arc::new(Upstream)),
            locker: Some(self.locker.clone()),
        })
    }

    pub fn lock(&self) -> lock::Lockfile {
        lock::read(&self.root()).unwrap().unwrap()
    }

    pub fn embedded(&self) -> Table {
        self.lock().provider_lock.unwrap()
    }

    pub fn rendered(&self) -> String {
        fs::read_to_string(self.root().join(".config/mise/mise.lock")).unwrap()
    }
}

/// The platform keys an embedded entry holds, sorted.
pub fn keys(embedded: &Table, tool: &str) -> Vec<String> {
    let mut out: Vec<String> = embedded["tools"][tool][0].as_table().unwrap().keys().filter_map(|k| k.strip_prefix("platforms.")).map(str::to_string).collect();
    out.sort();
    out
}

pub fn checksum(embedded: &Table, tool: &str, key: &str) -> String {
    embedded["tools"][tool][0][format!("platforms.{key}").as_str()]["checksum"].as_str().unwrap().into()
}

/// The checksum real mise wrote for `key`.
pub fn real(text: &str, tool: &str, key: &str) -> String {
    let lock: Table = toml::from_str(text).unwrap();
    lock["tools"][tool][0][format!("platforms.{key}").as_str()]["checksum"].as_str().unwrap().into()
}
