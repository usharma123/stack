//! A fake `mise lock` that writes the keys mise 2026.9.18 and 2026.10.3 write: for core:bun,
//! an unqualified `--platform` also writes Bun's build variants (`platform_variants` in
//! src/plugins/core/bun.rs); every other backend writes the requested key only. Tables for
//! bun 1.3.0 and node 24.13.0 are the ones real mise 2026.10.3 wrote (captured on macos-arm64,
//! `mise lock --platform linux-x64,linux-x64-musl,macos-arm64,macos-x64`); anything else gets a
//! synthetic table. Kept independent of stack's own variant table on purpose.

