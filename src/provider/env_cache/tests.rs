use super::*;
use crate::tool::ToolSpec;
use std::fs;

/// A checkout whose generated configuration pins jq, mise's data directory with that release
/// installed, a native `mise` (a link to /bin/sh, which is never run), and the answer mise
/// would give.
struct Fixture {
    _dir: tempfile::TempDir,
    base: PathBuf,
    root: PathBuf,
    state: PathBuf,
    data: PathBuf,
    bin: PathBuf,
}

const CONFIG: &str = r#"# Generated by `stack compile` from stack.toml + stack.lock. Do not edit.
[tools]
jq = "1.7.1"

[env]
DATABASE_URL = "postgresql://postgres@127.0.0.1:20001/postgres"
_.path = ["bin"]
"#;

const LOCK: &str = r#"lockfile_version = 3

[[tools.jq]]
version = "1.7.1"
backend = "aqua:jqlang/jq"
"#;

impl Fixture {
    fn new() -> Self {
        let dir = tempfile::tempdir().unwrap();
        let base = dir.path().canonicalize().unwrap();
        let root = base.join("app");
        let (state, data, bin) = (base.join("state"), base.join("mise-data"), base.join("bin"));
        fs::create_dir_all(root.join(".config/mise/conf.d")).unwrap();
        fs::write(root.join(".config/mise/conf.d/stack.toml"), CONFIG).unwrap();
        fs::write(root.join(".config/mise/mise.lock"), LOCK).unwrap();
        fs::create_dir_all(data.join("installs/jq/1.7.1/bin")).unwrap();
        fs::write(data.join("installs/jq/1.7.1/bin/jq"), "jq").unwrap();
        fs::create_dir_all(&bin).unwrap();
        std::os::unix::fs::symlink("/bin/sh", bin.join("mise")).unwrap();
        Self { _dir: dir, base, root, state, data, bin }
    }

    fn caller(&self) -> Caller {
        Caller(vec![
            ("PATH".into(), format!("{}:/usr/bin:/bin", self.bin.display()).into()),
            ("HOME".into(), self.base.clone().into()),
            ("MISE_DATA_DIR".into(), self.data.clone().into()),
        ])
    }

    fn with(&self, key: &str, value: &str) -> Caller {
        let mut caller = self.caller();
        caller.0.retain(|(k, _)| k != key);
        caller.0.push((key.into(), value.into()));
        caller
    }

    fn pins(&self) -> Vec<Pin> {
        vec![Pin { tool: "jq".into(), spec: ToolSpec { version: "1.7.1".into(), options: Default::default() } }]
    }

    fn install(&self) -> PathBuf {
        self.data.join("installs/jq/1.7.1")
    }

    /// What mise answers for the fixture.
    fn answer(&self) -> IndexMap<String, String> {
        IndexMap::from([
            ("DATABASE_URL".to_string(), "postgresql://postgres@127.0.0.1:20001/postgres".to_string()),
            ("PATH".to_string(), format!("{}/bin:{}/bin:{}:/usr/bin:/bin", self.install().display(), self.root.display(), self.bin.display())),
        ])
    }

    fn lookup(&self, caller: &Caller) -> Result<IndexMap<String, String>, Pending> {
        lookup(caller, &self.state, &self.root, &self.pins())
    }

    /// Ask as `caller` and keep `answer`, as asked after everything settled (the fixture was
    /// just made: its change times are now). Whether it was kept.
    fn keep_as(&self, caller: &Caller, answer: &IndexMap<String, String>, installs: &[PathBuf]) -> bool {
        let Err(mut pending) = self.lookup(caller) else { panic!("already kept") };
        pending.asked_at = SystemTime::now() + SETTLE + Duration::from_secs(1);
        remember(caller, &self.state, &self.root, &self.pins(), pending, answer, installs);
        self.lookup(caller).is_ok()
    }

    fn keep(&self) -> bool {
        self.keep_as(&self.caller(), &self.answer(), &[self.install()])
    }

    fn hit(&self) -> bool {
        self.lookup(&self.caller()).is_ok()
    }

    fn write(&self, rel: &str, text: &str) {
        let path = self.root.join(rel);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, text).unwrap();
    }
}

#[test]
fn a_kept_answer_is_found_again_as_mise_printed_it() {
    let fx = Fixture::new();
    assert!(fx.lookup(&fx.caller()).is_err());
    assert!(fx.keep());
    assert_eq!(fx.lookup(&fx.caller()).unwrap(), fx.answer());
}

#[test]
fn the_file_is_private_and_holds_nothing_mise_did_not_answer() {
    use std::os::unix::fs::PermissionsExt;
    let fx = Fixture::new();
    assert!(fx.keep());
    let file = path(&fx.state, &fx.root);
    assert_eq!(fs::metadata(&file).unwrap().permissions().mode() & 0o777, 0o600);
    // The caller's other variables are only in the key, as a digest.
    let caller = fx.with("API_TOKEN", "do-not-write-me");
    assert!(fx.keep_as(&caller, &fx.answer(), &[fx.install()]));
    assert!(!fs::read_to_string(&file).unwrap().contains("do-not-write-me"));
}

#[test]
fn an_answer_with_a_value_stack_cannot_account_for_is_not_kept() {
    let fx = Fixture::new();
    // A secret mise could only have taken from somewhere else (a template, a plugin).
    let mut answer = fx.answer();
    answer.insert("API_TOKEN".into(), "s3cret-value".into());
    assert!(!fx.keep_as(&fx.caller(), &answer, &[fx.install()]));
    assert!(!path(&fx.state, &fx.root).exists());
    // A configured value mise changed.
    let mut answer = fx.answer();
    answer.insert("DATABASE_URL".into(), "postgresql://elsewhere".into());
    assert!(!fx.keep_as(&fx.caller(), &answer, &[fx.install()]));
    // A PATH entry that is neither the caller's, an install's nor a declared path.
    let mut answer = fx.answer();
    answer.insert("PATH".into(), format!("/opt/elsewhere/bin:{}", fx.answer()["PATH"]));
    assert!(!fx.keep_as(&fx.caller(), &answer, &[fx.install()]));
    // A tool's own variable under its install directory is accounted for.
    let mut answer = fx.answer();
    answer.insert("JQ_HOME".into(), fx.install().display().to_string());
    assert!(fx.keep_as(&fx.caller(), &answer, &[fx.install()]));
}

#[test]
fn a_configuration_whose_answer_depends_on_more_is_never_kept() {
    let cases: &[(&str, &str, &str)] = &[
        ("a template", r#"FOO = "{{ env.HOME }}""#, LOCK),
        ("an exec template", r#"FOO = "{{ exec(command='date') }}""#, LOCK),
        ("a shell expansion", r#"FOO = "$HOME/x""#, LOCK),
        ("a plugin backend", "", "lockfile_version = 3\n\n[[tools.jq]]\nversion = \"1.7.1\"\nbackend = \"asdf:jq\"\n"),
        ("a vfox backend", "", "lockfile_version = 3\n\n[[tools.jq]]\nversion = \"1.7.1\"\nbackend = \"vfox:jq\"\n"),
        ("an unknown backend", "", "lockfile_version = 3\n\n[[tools.jq]]\nversion = \"1.7.1\"\nbackend = \"spaceship:jq\"\n"),
        ("no lock entry", "", "lockfile_version = 3\n"),
        ("another version locked", "", "lockfile_version = 3\n\n[[tools.jq]]\nversion = \"1.6\"\nbackend = \"aqua:jqlang/jq\"\n"),
    ];
    for (what, extra, lock) in cases {
        let fx = Fixture::new();
        fx.write(".config/mise/conf.d/stack.toml", &CONFIG.replace("[env]\n", &format!("[env]\n{extra}\n")));
        fx.write(".config/mise/mise.lock", lock);
        let mut answer = fx.answer();
        if !extra.is_empty() {
            answer.insert("FOO".into(), "x".into());
        }
        assert!(!fx.keep_as(&fx.caller(), &answer, &[fx.install()]), "{what}");
    }
    // A configured tool that is not a pin (an unversioned request, say).
    let fx = Fixture::new();
    fx.write(".config/mise/conf.d/stack.toml", &CONFIG.replace("jq = \"1.7.1\"", "jq = \"1.7.1\"\nnode = \"system\""));
    assert!(!fx.keep(), "a tool that is not a pin");
    // A pin whose install directory mise did not report.
    let fx = Fixture::new();
    assert!(!fx.keep_as(&fx.caller(), &fx.answer(), &[]), "an install not reported");
    // A `mise` that is a script: it runs some other file Stack cannot identify.
    let fx = Fixture::new();
    fs::remove_file(fx.bin.join("mise")).unwrap();
    fs::write(fx.bin.join("mise"), "#!/bin/sh\nexec /opt/homebrew/bin/mise \"$@\"\n").unwrap();
    fs::set_permissions(fx.bin.join("mise"), std::os::unix::fs::PermissionsExt::from_mode(0o755)).unwrap();
    assert!(key(&fx.caller(), &fx.root, &fx.pins()).is_none());
    assert!(!fx.lookup(&fx.caller()).unwrap_err().keepable());
    // No mise on PATH at all.
    let fx = Fixture::new();
    assert!(key(&fx.with("PATH", "/nonexistent"), &fx.root, &fx.pins()).is_none());
}

#[test]
fn the_generated_configuration_or_lock_changing_is_a_different_question() {
    let fx = Fixture::new();
    assert!(fx.keep());
    fx.write(".config/mise/conf.d/stack.toml", &CONFIG.replace("20001", "20002"));
    assert!(!fx.hit(), "configuration");
    fx.write(".config/mise/conf.d/stack.toml", CONFIG);
    assert!(fx.hit(), "the same content again is the same question");
    fx.write(".config/mise/mise.lock", &format!("{LOCK}\n# changed\n"));
    assert!(!fx.hit(), "lock");
    fs::remove_file(fx.root.join(".config/mise/mise.lock")).unwrap();
    assert!(!fx.hit(), "no lock");
}

