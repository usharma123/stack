#[test]
fn any_change_to_the_environment_mise_would_get_is_a_different_question() {
    let fx = Fixture::new();
    assert!(fx.keep());
    for (key, value) in [
        ("PATH", "/usr/local/bin:/usr/bin:/bin"),
        ("HOME", "/elsewhere"),
        ("MISE_DATA_DIR", "/elsewhere"),
        ("MISE_CACHE_DIR", "/elsewhere"),
        ("XDG_DATA_HOME", "/elsewhere"),
        ("UNRELATED", "1"),
    ] {
        let caller = if key == "PATH" { fx.with(key, &format!("{}:{value}", fx.bin.display())) } else { fx.with(key, value) };
        assert!(fx.lookup(&caller).is_err(), "{key}");
    }
    // Variables Stack never passes to mise (its configuration selection, the owner mark) are
    // not part of what mise reads.
    for key in ["MISE_ENV", "MISE_CONFIG_DIR", "MISE_OVERRIDE_CONFIG_FILENAMES", "__MISE_DIFF", "STACK_SUPERVISOR_OWNER"] {
        assert!(fx.lookup(&fx.with(key, "anything")).is_ok(), "{key}");
    }
}

#[test]
fn another_mise_binary_is_a_different_question() {
    let fx = Fixture::new();
    assert!(fx.keep());
    // Another binary behind the same name.
    fs::remove_file(fx.bin.join("mise")).unwrap();
    std::os::unix::fs::symlink("/bin/ls", fx.bin.join("mise")).unwrap();
    assert!(!fx.hit(), "relinked");
    // The same file replaced (an upgrade in place).
    fs::remove_file(fx.bin.join("mise")).unwrap();
    fs::copy("/bin/sh", fx.bin.join("mise")).unwrap();
    assert!(fx.keep());
    fs::copy("/bin/ls", fx.bin.join("mise")).unwrap();
    assert!(!fx.hit(), "replaced in place");
    // Another mise earlier on PATH.
    let fx = Fixture::new();
    assert!(fx.keep());
    let earlier = fx.base.join("earlier");
    fs::create_dir_all(&earlier).unwrap();
    std::os::unix::fs::symlink("/bin/ls", earlier.join("mise")).unwrap();
    assert!(fx.lookup(&fx.with("PATH", &format!("{}:{}:/usr/bin:/bin", earlier.display(), fx.bin.display()))).is_err());
}

#[test]
fn installing_removing_or_reinstalling_a_release_is_seen() {
    // A file added to the release (mise finishing an install into it, a reinstall's contents).
    let fx = Fixture::new();
    assert!(fx.keep());
    fs::write(fx.install().join("extra"), "x").unwrap();
    assert!(!fx.hit(), "an entry added to the release");
    // Its bin directory gaining a program (mise's `.mise-bins` links, say).
    let fx = Fixture::new();
    assert!(fx.keep());
    fs::write(fx.install().join("bin/jq-extra"), "x").unwrap();
    assert!(!fx.hit(), "a program added to its bin directory");
    // Removed.
    let fx = Fixture::new();
    assert!(fx.keep());
    fs::remove_dir_all(fx.install()).unwrap();
    assert!(!fx.hit(), "removed");
    // Removed and installed again, the same way.
    let fx = Fixture::new();
    assert!(fx.keep());
    fs::remove_dir_all(fx.install()).unwrap();
    fs::create_dir_all(fx.install().join("bin")).unwrap();
    fs::write(fx.install().join("bin/jq"), "jq").unwrap();
    assert!(!fx.hit(), "reinstalled");
    // Another release installed beside it (and mise's `latest` link moving).
    let fx = Fixture::new();
    assert!(fx.keep());
    fs::create_dir_all(fx.data.join("installs/jq/1.8.0")).unwrap();
    assert!(!fx.hit(), "another release beside it");
    // Its backend record rewritten.
    let fx = Fixture::new();
    fs::write(fx.data.join("installs/jq/.mise.backend.toml"), "a").unwrap();
    assert!(fx.keep());
    fs::write(fx.data.join("installs/jq/.mise.backend.toml"), "bb").unwrap();
    assert!(!fx.hit(), "backend record");
}

#[test]
fn a_change_racing_the_question_is_never_kept() {
    let fx = Fixture::new();
    // Asked now: the install directory changed just before (the fixture was just made), so it
    // may have changed while mise answered.
    let Err(pending) = fx.lookup(&fx.caller()) else { panic!() };
    remember(&fx.caller(), &fx.state, &fx.root, &fx.pins(), pending, &fx.answer(), &[fx.install()]);
    assert!(!fx.hit());
    // The configuration changed between the lookup and keeping the answer.
    let Err(mut pending) = fx.lookup(&fx.caller()) else { panic!() };
    pending.asked_at = SystemTime::now() + SETTLE + Duration::from_secs(1);
    fx.write(".config/mise/conf.d/stack.toml", &CONFIG.replace("20001", "20003"));
    remember(&fx.caller(), &fx.state, &fx.root, &fx.pins(), pending, &fx.answer(), &[fx.install()]);
    fx.write(".config/mise/conf.d/stack.toml", CONFIG);
    assert!(!fx.hit());
}

#[test]
fn concurrent_commands_never_see_a_torn_file() {
    let fx = Fixture::new();
    let callers: Vec<Caller> = (0..8).map(|i| fx.with("AGENT", &i.to_string())).collect();
    std::thread::scope(|scope| {
        for caller in &callers {
            let fx = &fx;
            scope.spawn(move || {
                for _ in 0..20 {
                    match fx.lookup(caller) {
                        Ok(env) => assert_eq!(env, fx.answer()),
                        Err(mut pending) => {
                            pending.asked_at = SystemTime::now() + SETTLE + Duration::from_secs(1);
                            remember(caller, &fx.state, &fx.root, &fx.pins(), pending, &fx.answer(), &[fx.install()]);
                        }
                    }
                    let text = fs::read(path(&fx.state, &fx.root)).unwrap_or_default();
                    assert!(text.is_empty() || serde_json::from_slice::<CacheFile>(&text).is_ok(), "a torn file");
                }
            });
        }
    });
    // Each caller's last write kept at most MAX_ENTRIES answers, all valid.
    let file = read(&fx.state, &fx.root);
    assert!(!file.entries.is_empty() && file.entries.len() <= MAX_ENTRIES);
}

