#[test]
fn an_answer_kept_already_is_not_written_again() {
    let fx = Fixture::new();
    let Err(mut first) = fx.lookup(&fx.caller()) else { panic!() };
    let Err(mut second) = fx.lookup(&fx.caller()) else { panic!() };
    first.asked_at = SystemTime::now() + SETTLE + Duration::from_secs(1);
    second.asked_at = first.asked_at;
    remember(&fx.caller(), &fx.state, &fx.root, &fx.pins(), first, &fx.answer(), &[fx.install()]);
    let file = path(&fx.state, &fx.root);
    let written = fs::metadata(&file).unwrap();
    std::thread::sleep(Duration::from_millis(20));
    remember(&fx.caller(), &fx.state, &fx.root, &fx.pins(), second, &fx.answer(), &[fx.install()]);
    use std::os::unix::fs::MetadataExt;
    assert_eq!(fs::metadata(&file).unwrap().ino(), written.ino(), "rewritten");
}
