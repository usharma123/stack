#[test]
fn a_path_whose_mise_cannot_be_told_from_here_identifies_nothing() {
    let fx = Fixture::new();
    // A script named mise in the checkout, which an empty or relative entry would run (mise is
    // started in the checkout), ahead of the native one.
    fs::write(fx.root.join("mise"), "#!/bin/sh\nexec /bin/sh \"$@\"\n").unwrap();
    fs::set_permissions(fx.root.join("mise"), std::os::unix::fs::PermissionsExt::from_mode(0o755)).unwrap();
    let bin = fx.bin.display();
    for path in [format!(":{bin}"), format!("/usr/local/bin::{bin}"), format!(".:{bin}"), format!("rel/bin:{bin}")] {
        assert!(key(&fx.with("PATH", &path), &fx.root, &fx.pins()).is_none(), "{path}");
    }
    // An empty or relative entry after the one that matched changes nothing.
    assert!(key(&fx.with("PATH", &format!("{}::rel", fx.bin.display())), &fx.root, &fx.pins()).is_some());
}

