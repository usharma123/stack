#[test]
fn render_and_capture_are_inverses_on_real_output() {
    let (lock, stripped) = captured();
    assert_eq!(stripped, [pin("npm:prettier", "3.6.2")], "the npm sidecar reference is stripped");
    let embedded = finish(lock.clone(), None, stripped, &real_pins(), &platforms(&["macos-arm64", "linux-x64"]));
    assert_eq!(embedded.keys().next().map(String::as_str), Some("provider"));
    let rendered = render(&embedded);
    let (again, none) = capture(&rendered).unwrap();
    assert!(none.is_empty());
    assert_eq!(again, lock, "render then capture gives the captured lock back");
    // Everything but the sidecar reference survives, compared as parsed documents.
    let mut original: Table = toml::from_str(REAL).unwrap();
    original["tools"]["npm:prettier"][0].as_table_mut().unwrap().remove("aube");
    assert_eq!(to_mise(&embedded), original);
    assert!(!rendered.contains("aube") && !rendered.contains("stack_sidecars") && !rendered.contains("provider ="), "{rendered}");
    let doc: Table = toml::from_str(&rendered).unwrap();
    assert_eq!(doc["tools"]["swift"].as_array().unwrap().len(), 2, "both options variants of one version are kept");
    assert_eq!(doc["tools"]["jq"][0]["future_field"].as_str(), Some("a newer mise wrote this"));
    assert_eq!(doc["tools"]["fnox"][0]["platforms.macos-arm64"]["repository_ids"]["repository"].as_str(), Some("1078762196"));
    assert!(doc["tools"]["jq"][0]["platforms.macos-arm64"]["url_api"].is_str());
    // And it survives stack.lock's own serialization.
    let lock_file = crate::lock::Lockfile { provider_lock: Some(embedded.clone()), ..crate::lock::Lockfile::new(vec![], vec![], vec![]) };
    let text = toml::to_string_pretty(&lock_file).unwrap();
    let back: crate::lock::Lockfile = toml::from_str(&text).unwrap();
    assert_eq!(back.provider_lock.as_ref(), Some(&embedded));
}

#[test]
fn coverage_follows_the_backend_and_the_platform_entry() {
    let (lock, stripped) = captured();
    let embedded = finish(lock, None, stripped, &real_pins(), &platforms(&["macos-arm64", "linux-x64"]));
    let state = |tool: &str, version: &str, platform: &str| coverage(Some(&embedded), &pin(tool, version), platform).state;
    assert_eq!(state("fnox", "1.39.0", "macos-arm64"), State::Verified);
    assert_eq!(state("jq", "1.7.1", "linux-x64"), State::Verified);
    assert_eq!(state("python", "3.13.2", "macos-arm64"), State::Verified);
    assert_eq!(state("postgres", "17.6", "macos-arm64"), State::Verified);
    assert_eq!(state("postgres", "17.6", "linux-x64"), State::Missing, "no entry for the platform");
    assert_eq!(state("jq", "1.7.1", "macos-x64"), State::Missing);
    assert_eq!(state("jq", "1.8.0", "linux-x64"), State::Missing, "another version");
    assert_eq!(state("rust", "1.93.1", "linux-arm64"), State::Exempt);
    assert_eq!(state("npm:prettier", "3.6.2", "macos-arm64"), State::Unsupported);
    // Unlocked releases are classified by the name when it names a backend.
    assert_eq!(coverage(None, &pin("cargo:ripgrep", "14.1.0"), "linux-x64").state, State::Exempt);
    assert_eq!(coverage(None, &pin("pipx:black", "24.1.0"), "linux-x64").state, State::Unsupported);
    assert_eq!(coverage(None, &pin("vfox:nodejs", "20.0.0"), "linux-x64").state, State::Missing, "plain vfox records URLs");
    let c = coverage(Some(&embedded), &pin("fnox", "1.39.0"), "macos-arm64");
    assert_eq!(c.checksum.as_deref(), Some("sha256:5604196e7a0aafb949251be1ae088bf0bb524edbfb45748d1be0cbc46e98b8f5"));
    assert!(c.signer.unwrap().starts_with("sigstore-oidc:"));

    // A packslip entry without its signer is not called verified; nor is a URL without checksum.
    let mut weak = embedded.clone();
    weak["tools"]["fnox"][0]["platforms.macos-arm64"].as_table_mut().unwrap().remove("signer");
    weak["tools"]["jq"][0]["platforms.linux-x64"].as_table_mut().unwrap().remove("checksum");
    assert_eq!(coverage(Some(&weak), &pin("fnox", "1.39.0"), "macos-arm64").state, State::Missing);
    assert_eq!(coverage(Some(&weak), &pin("jq", "1.7.1"), "linux-x64").state, State::Missing);

    // An unusual backend that carried a sidecar stays unsupported after the reference is gone.
    let custom = "[[tools.mytool]]\nversion = \"1.0.0\"\nbackend = \"vfox-custom:mytool\"\nsidecar = { path = \"locks/x\", digest = \"sha256:00\" }\n";
    let (lock, stripped) = capture(custom).unwrap();
    assert_eq!(stripped, [pin("mytool", "1.0.0")]);
    let embedded = finish(lock, None, stripped, &[pin("mytool", "1.0.0")], &platforms(&["linux-x64"]));
    let text = toml::to_string(&embedded).unwrap();
    let back: Table = toml::from_str(&text).unwrap();
    assert_eq!(coverage(Some(&back), &pin("mytool", "1.0.0"), "linux-x64").state, State::Unsupported);
    assert!(!render(&back).contains("sidecar"));
}

#[test]
fn partitions_keep_every_version_of_a_name_together() {
    let (lock, stripped) = captured();
    let embedded = finish(lock, None, stripped, &real_pins(), &platforms(&["macos-arm64", "linux-x64"]));
    let pins = vec![pin("jq", "1.7.1"), pin("rust", "1.93.1"), pin("npm:prettier", "3.6.2"), pin("postgres", "17.6"), pin("postgres", "16.4"), pin("fnox", "1.39.0")];
    let p = partition(Some(&embedded), &pins, "macos-arm64");
    assert_eq!(p.locked, ["jq", "rust", "fnox"]);
    assert_eq!(p.plain, ["npm:prettier", "postgres"], "postgres@16.4 is missing, so the name goes plain");
    let s = summary(Some(&embedded), &pins, "macos-arm64");
    assert_eq!(s.verified, ["jq@1.7.1", "postgres@17.6", "fnox@1.39.0"]);
    assert_eq!((s.exempt.len(), s.unsupported.len(), s.missing.clone()), (1, 1, vec!["postgres@16.4".to_string()]));
    let empty = partition(None, &[], "macos-arm64");
    assert!(empty.locked.is_empty() && empty.plain.is_empty());
}

#[test]
fn validation_names_entries_that_disagree_with_pins_and_dangling_dependencies() {
    let (lock, stripped) = captured();
    let embedded = finish(lock, None, stripped, &real_pins(), &platforms(&["macos-arm64", "linux-x64"]));
    validate(&embedded, &real_pins()).unwrap();
    let mut pins = real_pins();
    pins.retain(|p| p.tool != "jq");
    pins.push(pin("jq", "1.8.0"));
    let e = validate(&embedded, &pins).unwrap_err();
    assert_eq!(e.code, "lock_invalid");
    assert!(e.message.contains("tools.jq") && e.message.contains("1.7.1"), "{e:?}");
    let mut dangling = embedded.clone();
    dangling["conda-packages"]["macos-arm64"].as_table_mut().unwrap().remove("openssl-3.6.5-h5503f6c_0");
    let e = validate(&dangling, &real_pins()).unwrap_err();
    assert_eq!(e.code, "lock_invalid");
    assert_eq!(e.details[0]["dep"], "openssl-3.6.5-h5503f6c_0", "{e:?}");
}

#[test]
fn retain_drops_unpinned_entries_unlisted_platforms_and_unreferenced_records() {
    let (lock, stripped) = captured();
    let mut embedded = finish(lock, None, stripped, &real_pins(), &platforms(&["macos-arm64", "linux-x64"]));
    let pins = vec![pin("jq", "1.7.1"), pin("postgres", "17.6")];
    retain(&mut embedded, &pins, &platforms(&["linux-x64"]));
    let tools = embedded["tools"].as_table().unwrap();
    assert_eq!(tools.keys().collect::<Vec<_>>(), ["jq", "postgres"]);
    assert!(tools["jq"][0].get("platforms.macos-arm64").is_none() && tools["jq"][0].get("platforms.linux-x64").is_some());
    assert!(embedded.get("conda-packages").is_none(), "macos-arm64 records go with the platform");
    assert!(embedded.get("stack_sidecars").is_none(), "npm:prettier is no longer pinned");
}

fn merge(committed: Option<&Table>, fresh: &str, targets: &[&str], pins: &[PinKey], update: bool, reasons: &Reasons) -> Result<Merged> {
    let (fresh, _) = capture(fresh).unwrap();
    let targets: BTreeSet<String> = targets.iter().map(|t| t.to_string()).collect();
    Merge { committed, fresh, targets: &targets, pins, platforms: &platforms(&["macos-arm64", "linux-x64"]), update, reasons, changed: &BTreeSet::new() }.run()
}

