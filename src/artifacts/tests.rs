#[test]
fn update_merges_accept_changes_and_never_report_a_skipped_refresh_as_one() {
    let (committed, _) = captured();
    let pins = real_pins();
    let m = merge(Some(&committed), JQ_FRESH, &["jq"], &pins, true, &Reasons::new()).unwrap();
    let jq = &m.lock["tools"]["jq"][0];
    assert_eq!(jq["platforms.linux-x64"]["checksum"].as_str(), Some("sha256:ffff"));
    let e = &m.events[&(pin("jq", "1.7.1"), "linux-x64".into())];
    assert_eq!(e.change, Some("artifact_changed"));
    assert_eq!(e.checksum_was.as_deref(), Some("sha256:5942c9b0934e510ee61eb3e30273f1b3fe2590df93933a93d7c58b81d19c8ff5"));
    assert!(e.url_was.is_some());
    assert!(!m.events.contains_key(&(pin("jq", "1.7.1"), "macos-arm64".into())), "an unchanged value is not reported");

    // Offline: mise keeps no entry for jq (the seed had none), exits 0, and says nothing.
    let m = merge(Some(&committed), "lockfile_version = 3\n", &["jq"], &pins, true, &Reasons::new()).unwrap();
    assert_eq!(m.lock["tools"]["jq"][0]["platforms.linux-x64"], committed["tools"]["jq"][0]["platforms.linux-x64"]);
    for platform in ["linux-x64", "macos-arm64"] {
        let e = &m.events[&(pin("jq", "1.7.1"), platform.into())];
        assert_eq!(e.change, Some("retained"), "{platform}");
        assert!(e.reason.as_deref().unwrap().contains("committed value is kept"));
    }
    // A platform the fresh entry lacks is retained with mise's reason.
    let partial = JQ_FRESH.split("[tools.jq.\"platforms.macos-arm64\"]").next().unwrap();
    let reasons: Reasons = [(("jq".to_string(), "macos-arm64".to_string()), "failed to resolve jq for macos-arm64: offline".to_string())].into();
    let m = merge(Some(&committed), partial, &["jq"], &pins, true, &reasons).unwrap();
    let e = &m.events[&(pin("jq", "1.7.1"), "macos-arm64".into())];
    assert_eq!((e.change, e.reason.as_deref()), (Some("retained"), Some("failed to resolve jq for macos-arm64: offline")));
    assert!(m.lock["tools"]["jq"][0].get("platforms.macos-arm64").is_some());
}

